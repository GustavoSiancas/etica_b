"""Generate the participant INSERT seed from the supplied CSV (Python stdlib only)."""
from __future__ import annotations

import argparse
import csv
import io
import os
from pathlib import Path
import re
import sys
import tempfile
from dataclasses import dataclass

COLUMNS = ("numero_de_cal", "nombre_completo", "tipo_documento", "numero_documento")
ROOT = Path(__file__).resolve().parents[1]

@dataclass(frozen=True)
class Participant:
    registration_number: int
    name: str
    document_type: str
    document_number: str

@dataclass
class ImportResult:
    participants: list[Participant]
    rejected: list[dict[str, str]]
    source_rows: int
    repeated_documents: int


def read_participants(source: Path, encoding: str = "utf-8-sig", delimiter: str | None = None) -> ImportResult:
    # Decode strictly: replacing undecodable characters would corrupt names.
    text = source.read_text(encoding=encoding)
    if delimiter is None:
        try:
            delimiter = csv.Sniffer().sniff(text[:8192], delimiters=",;\t|").delimiter
        except csv.Error:
            raise ValueError("No se pudo detectar el separador; indicar --delimiter.") from None
    reader = csv.DictReader(io.StringIO(text, newline=""), delimiter=delimiter, strict=True)
    if reader.fieldnames is None:
        raise ValueError("El CSV no tiene encabezados.")
    headers = [name.strip().lower().lstrip("\ufeff") for name in reader.fieldnames]
    if len(set(headers)) != len(headers) or not set(COLUMNS).issubset(headers):
        raise ValueError("Se requieren columnas unicas: " + ", ".join(COLUMNS))
    reader.fieldnames = headers
    participants: list[Participant] = []
    rejected: list[dict[str, str]] = []
    registrations: set[int] = set()
    documents: set[tuple[str, str]] = set()
    source_rows = repeated_documents = 0
    for raw in reader:
        if not any(value for value in raw.values()):
            continue
        source_rows += 1
        row = {name: (raw.get(name) or "").strip() for name in COLUMNS}
        row["tipo_documento"] = row["tipo_documento"].upper()
        issues = []
        if None in raw or any(raw.get(name) is None for name in COLUMNS):
            issues.append("cantidad de columnas incorrecta")
        cal = row["numero_de_cal"]
        registration = int(cal) if re.fullmatch(r"[0-9]{1,19}", cal) else 0
        if not 0 < registration <= 9223372036854775807:
            issues.append("numero_de_cal debe ser entero positivo BIGINT")
        if registration in registrations:
            issues.append("numero_de_cal repetido en el CSV")
        name = row["nombre_completo"]
        if not name or len(name) > 255 or "\x00" in name:
            issues.append("nombre_completo obligatorio de hasta 255 caracteres, sin NUL")
        if row["tipo_documento"] not in {"DNI", "CE"}:
            issues.append("tipo_documento debe ser DNI o CE")
        if not re.fullmatch(r"[0-9]{1,20}", row["numero_documento"]):
            issues.append("numero_documento debe contener de 1 a 20 digitos")
        if issues:
            rejected.append({"linea": str(reader.line_num), **row, "motivo": "; ".join(issues)})
            continue
        registrations.add(registration)
        key = (row["tipo_documento"], row["numero_documento"])
        if key in documents:
            repeated_documents += 1
        documents.add(key)
        participants.append(Participant(registration, name, row["tipo_documento"], row["numero_documento"]))
    return ImportResult(participants, rejected, source_rows, repeated_documents)


def sql_text(value: str) -> str:
    # E-strings escape backslashes independently of server string settings.
    return "E'" + value.replace("\\", "\\\\").replace("'", "''") + "'"


def generate_sql(participants: list[Participant]) -> str:
    if not participants:
        raise ValueError("No hay registros validos; no se reemplazo el SQL.")
    statements = ["""-- Generated by scripts/import_participants.py; do not edit individual rows.
-- Only inserts denunciados. Existing rows are never updated or deleted.
-- Registration number (CAL) identifies a participant for this import.
BEGIN;
CREATE TEMP TABLE seed_denunciados (
    registration_number BIGINT PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    document_type VARCHAR(3) NOT NULL,
    document_number VARCHAR(20) NOT NULL
) ON COMMIT DROP;
"""]
    for start in range(0, len(participants), 1000):
        values = [f"({p.registration_number}, {sql_text(p.name)}, {sql_text(p.document_type)}, {sql_text(p.document_number)})"
                  for p in participants[start:start + 1000]]
        statements.append("INSERT INTO seed_denunciados (registration_number, name, document_type, document_number) VALUES\n" + ",\n".join(values) + ";\n")
    statements.append("""
-- Serialize concurrent import/startup and participant INSERT operations.
LOCK TABLE denunciados IN SHARE ROW EXCLUSIVE MODE;
INSERT INTO denunciados (registration_number, name, document_type, document_number)
SELECT s.registration_number, s.name, s.document_type, s.document_number
FROM seed_denunciados s
WHERE NOT EXISTS (
    SELECT 1 FROM denunciados d WHERE d.registration_number = s.registration_number
)
ORDER BY s.registration_number;
COMMIT;
""")
    return "\n".join(statements)


def write_atomic(path: Path, value: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", newline="\n", dir=path.parent, delete=False) as f:
            temporary = f.name
            f.write(value)
        os.replace(temporary, path)
    finally:
        if temporary is not None and os.path.exists(temporary):
            os.unlink(temporary)


def write_report(path: Path, rows: list[dict[str, str]]) -> None:
    stream = io.StringIO(newline="")
    writer = csv.DictWriter(stream, fieldnames=["linea", *COLUMNS, "motivo"], delimiter=";")
    writer.writeheader()
    writer.writerows(rows)
    write_atomic(path, stream.getvalue())


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="CSV de colegiados a seeds/demo_data.sql; no conecta a la base de datos.")
    parser.add_argument("source", type=Path)
    parser.add_argument("--output", type=Path, default=ROOT / "seeds" / "demo_data.sql")
    parser.add_argument("--report", type=Path, default=ROOT / ".cache" / "import_rejected.csv")
    parser.add_argument("--encoding", default="utf-8-sig")
    parser.add_argument("--delimiter", help="Separador CSV; por defecto se detecta.")
    parser.add_argument("--skip-invalid", action="store_true", help="Generar SQL solo con filas validas; guardar rechazadas en el reporte.")
    args = parser.parse_args(argv)
    try:
        if args.delimiter is not None and len(args.delimiter) != 1:
            raise ValueError("--delimiter debe ser un caracter.")
        if args.source.resolve() in {args.output.resolve(), args.report.resolve()} or args.output.resolve() == args.report.resolve():
            raise ValueError("Origen, SQL y reporte deben ser archivos distintos.")
        result = read_participants(args.source, args.encoding, args.delimiter)
        write_report(args.report, result.rejected)
        if result.rejected and not args.skip_invalid:
            raise ValueError(f"{len(result.rejected)} filas invalidas; revisar el reporte. SQL sin cambios. Usar --skip-invalid para omitirlas explicitamente.")
        write_atomic(args.output, generate_sql(result.participants))
        print(f"Filas: {result.source_rows}; validas: {len(result.participants)}; rechazadas: {len(result.rejected)}; documentos repetidos con distinto CAL: {result.repeated_documents}.")
        print(f"SQL: {args.output}\nReporte: {args.report}")
        return 0
    except (OSError, UnicodeError, ValueError, csv.Error) as err:
        print(f"Error: {err}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())

package services

import (
	"context"
	"fmt"
	"net/url"
	"os"
	"path/filepath"
	"strings"
	"sync"
	"testing"
	"time"

	"etica_back/internal/config"
	platform "etica_back/internal/platform/postgres"
	"github.com/jackc/pgx/v5"
)

// Opt in against local PostgreSQL; all data stays in an isolated disposable schema.
func TestAutomaticCodesPostgres(t *testing.T) {
	if os.Getenv("ETICA_INTEGRATION") != "1" {
		t.Skip("set ETICA_INTEGRATION=1 to test PostgreSQL")
	}
	cwd, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	if err = os.Chdir(filepath.Join(cwd, "../..")); err != nil {
		t.Fatal(err)
	}
	defer os.Chdir(cwd)
	cfg, err := config.Load()
	if err != nil {
		t.Fatal("configuration unavailable")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	admin, pool, err := platform.Open(ctx, cfg.DatabaseURL)
	if err != nil {
		t.Fatal(platform.Diagnose(err))
	}
	defer pool.Close()
	schema := fmt.Sprintf("etica_code_test_%d", time.Now().UnixNano())
	quoted := pgx.Identifier{schema}.Sanitize()
	if err = admin.Exec("CREATE SCHEMA " + quoted).Error; err != nil {
		t.Fatal("cannot create isolated test schema")
	}
	defer func() {
		if err := admin.Exec("DROP SCHEMA " + quoted + " CASCADE").Error; err != nil {
			t.Error("cannot clean test schema")
		}
	}()
	u, _ := url.Parse(cfg.DatabaseURL)
	q := u.Query()
	q.Set("search_path", schema)
	u.RawQuery = q.Encode()
	db, testPool, err := platform.Open(ctx, u.String())
	if err != nil {
		t.Fatal(platform.Diagnose(err))
	}
	defer testPool.Close()
	if err = db.Exec(`CREATE TABLE expedientes (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, number VARCHAR(50) NOT NULL UNIQUE,name VARCHAR(255) NOT NULL DEFAULT '',opening_date DATE,status VARCHAR(30) NOT NULL DEFAULT 'OPEN',created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW())`).Error; err != nil {
		t.Fatal("cannot create test table")
	}
	// Verify bootstrap continues existing canonical codes without renumbering legacy data.
	if err = db.Exec(`INSERT INTO expedientes(number) VALUES ('9-2026'),('LEGACY-001')`).Error; err != nil {
		t.Fatal("cannot create migration fixtures")
	}
	migration, err := os.ReadFile("migrations/002_expediente_codes.up.sql")
	if err != nil {
		t.Fatal(err)
	}
	if err = db.Exec(string(migration)).Error; err != nil {
		t.Fatal("migration failed")
	}
	initMigration, err := os.ReadFile("migrations/003_expediente_init_types.up.sql")
	if err != nil {
		t.Fatal(err)
	}
	if err = db.Exec(string(initMigration)).Error; err != nil {
		t.Fatal("init types migration failed")
	}
	enumMigration, err := os.ReadFile("migrations/004_expediente_init_enum.up.sql")
	if err != nil {
		t.Fatal(err)
	}
	if err = db.Exec(string(enumMigration)).Error; err != nil {
		t.Fatal("init enum migration failed")
	}
	var legacy string
	if err = db.Raw("SELECT code FROM expedientes WHERE number='LEGACY-001'").Scan(&legacy).Error; err != nil || legacy != "LEGACY-001" {
		t.Fatal("legacy identifier changed")
	}
	var year int
	if err = db.Raw("SELECT EXTRACT(YEAR FROM statement_timestamp() AT TIME ZONE 'America/Lima')::integer").Scan(&year).Error; err != nil {
		t.Fatal("cannot read Lima year")
	}
	service := NewExpedienteService(db)
	first, err := service.Create(ctx, CreateExpedienteInput{InitType: "DENUNCIA_DE_OFICIO"})
	if err != nil {
		t.Fatal("create failed")
	}
	expectedFirst := fmt.Sprintf("1-%d", year)
	if year == 2026 {
		expectedFirst = "10-2026"
	}
	if first.Code != expectedFirst || first.Number != first.Code || first.CreatedAt.IsZero() {
		t.Fatalf("incorrect generated response: %+v", first)
	}
	const count = 12
	results := make(chan ExpedienteResponse, count)
	errs := make(chan error, count)
	var group sync.WaitGroup
	for i := 0; i < count; i++ {
		group.Add(1)
		go func() {
			defer group.Done()
			result, err := service.Create(ctx, CreateExpedienteInput{InitType: "DENUNCIA_DE_OFICIO"})
			if err != nil {
				errs <- err
				return
			}
			results <- result
		}()
	}
	group.Wait()
	close(results)
	close(errs)
	if len(errs) > 0 {
		t.Fatal("concurrent creation failed")
	}
	codes := map[string]bool{first.Code: true}
	for result := range results {
		if codes[result.Code] {
			t.Fatal("duplicate code")
		}
		codes[result.Code] = true
	}
	for _, test := range []struct {
		year int
		want string
	}{{year + 1, fmt.Sprintf("1-%d", year+1)}, {year + 1, fmt.Sprintf("2-%d", year+1)}, {year + 2, fmt.Sprintf("1-%d", year+2)}} {
		var got string
		if err = db.Raw("SELECT next_expediente_code(?)", test.year).Scan(&got).Error; err != nil || got != test.want {
			t.Fatalf("annual sequence: got %s want %s", got, test.want)
		}
	}
	tx := db.Begin()
	var rolledBack string
	if err = tx.Raw("SELECT next_expediente_code(?)", year+3).Scan(&rolledBack).Error; err != nil {
		tx.Rollback()
		t.Fatal("counter allocation failed")
	}
	tx.Rollback()
	var retried string
	if err = db.Raw("SELECT next_expediente_code(?)", year+3).Scan(&retried).Error; err != nil || retried != rolledBack {
		t.Fatal("counter did not roll back")
	}
	list, err := service.List(ctx, 100, 0)
	if err != nil || list.Total != count+3 {
		t.Fatal("list failed")
	}
	if err = db.Exec("UPDATE expedientes SET code=NULL WHERE id=?", first.ID).Error; err == nil {
		t.Fatal("accepted null code")
	}
	if err = db.Exec("UPDATE expedientes SET code=? WHERE number='LEGACY-001'", first.Code).Error; err == nil {
		t.Fatal("accepted duplicate code")
	}
	down, err := os.ReadFile("migrations/004_expediente_init_enum.down.sql")
	if err != nil {
		t.Fatal(err)
	}
	if err = db.Exec(strings.TrimSpace(string(down))).Error; err != nil {
		t.Fatal("init enum down migration failed")
	}
	down, err = os.ReadFile("migrations/003_expediente_init_types.down.sql")
	if err != nil {
		t.Fatal(err)
	}
	if err = db.Exec(strings.TrimSpace(string(down))).Error; err != nil {
		t.Fatal("init types down migration failed")
	}
	down, err = os.ReadFile("migrations/002_expediente_codes.down.sql")
	if err != nil {
		t.Fatal(err)
	}
	if err = db.Exec(strings.TrimSpace(string(down))).Error; err != nil {
		t.Fatal("down migration failed")
	}
}

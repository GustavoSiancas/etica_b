BEGIN;
SELECT pg_advisory_xact_lock(8020, 10);
CREATE TABLE IF NOT EXISTS app_schema_migrations (
 version VARCHAR(100) PRIMARY KEY,
 applied_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
DO $upgrade$
BEGIN
 IF EXISTS (SELECT 1 FROM app_schema_migrations WHERE version='010_expediente_history') THEN RETURN; END IF;
 CREATE TABLE expediente_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  expediente_id BIGINT NOT NULL REFERENCES expedientes(id) ON DELETE RESTRICT,
  folder_id BIGINT,
  folder_name TEXT,
  event TEXT NOT NULL,
  status VARCHAR(30) NOT NULL CHECK (status IN ('ABIERTO','CERRADO')),
  opening_date TIMESTAMPTZ,
  closing_date TIMESTAMPTZ,
  changed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  active_folders JSONB NOT NULL CHECK (jsonb_typeof(active_folders) = 'array'),
  FOREIGN KEY (expediente_id, folder_id) REFERENCES expediente_folders(expediente_id,id) ON DELETE RESTRICT,
  CHECK ((folder_id IS NULL) = (folder_name IS NULL))
 );
 CREATE INDEX idx_expediente_history_timeline ON expediente_history(expediente_id,changed_at DESC,id DESC);
 INSERT INTO app_schema_migrations(version) VALUES ('010_expediente_history');
END;
$upgrade$;
COMMIT;

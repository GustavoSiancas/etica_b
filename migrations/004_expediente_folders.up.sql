BEGIN;
SELECT pg_advisory_xact_lock(8020, 4);
CREATE TABLE IF NOT EXISTS app_schema_migrations (
    version VARCHAR(100) PRIMARY KEY,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
DO $upgrade$
BEGIN
    IF EXISTS (SELECT 1 FROM app_schema_migrations WHERE version='004_expediente_folders') THEN
        RETURN;
    END IF;
    LOCK TABLE expedientes, expediente_section IN SHARE ROW EXCLUSIVE MODE;
    CREATE TABLE folder_types (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL UNIQUE CHECK (btrim(name) <> '')
    );
    INSERT INTO folder_types(name) VALUES ('EXPEDIENTE PRINCIPAL'), ('EXPEDIENTE CAUTELAR');
    CREATE TABLE expediente_folders (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        expediente_id BIGINT NOT NULL REFERENCES expedientes(id) ON DELETE RESTRICT,
        folder_type_id BIGINT NOT NULL REFERENCES folder_types(id) ON DELETE RESTRICT,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        UNIQUE (expediente_id, folder_type_id),
        UNIQUE (expediente_id, id)
    );
    INSERT INTO expediente_folders(expediente_id, folder_type_id)
    SELECT e.id, t.id FROM expedientes e CROSS JOIN folder_types t
    WHERE t.name='EXPEDIENTE PRINCIPAL';
    ALTER TABLE expediente_section ADD COLUMN expediente_folder_id BIGINT;
    UPDATE expediente_section s SET expediente_folder_id=f.id
    FROM expediente_folders f WHERE f.expediente_id=s.expediente_id;
    ALTER TABLE expediente_section
        ALTER COLUMN expediente_folder_id SET NOT NULL,
        ADD CONSTRAINT section_folder_fk FOREIGN KEY (expediente_id, expediente_folder_id)
            REFERENCES expediente_folders(expediente_id, id) ON DELETE RESTRICT,
        ADD CONSTRAINT section_folder_identity UNIQUE (expediente_folder_id, id),
        ADD CONSTRAINT section_parent_folder_fk FOREIGN KEY (expediente_folder_id, expediente_section_parent_id)
            REFERENCES expediente_section(expediente_folder_id, id) ON DELETE RESTRICT;
    CREATE INDEX idx_section_folder_tree ON expediente_section
        (expediente_folder_id, expediente_section_parent_id, sort_order, id);
    -- Keep older section writers compatible; descendants inherit their parent's folder.
    EXECUTE $function$
        CREATE FUNCTION assign_section_folder() RETURNS trigger LANGUAGE plpgsql AS $$
        BEGIN
            IF NEW.expediente_folder_id IS NULL OR NEW.expediente_folder_id=0 THEN
                IF NEW.expediente_section_parent_id IS NOT NULL THEN
                    SELECT expediente_folder_id INTO NEW.expediente_folder_id
                    FROM expediente_section WHERE id=NEW.expediente_section_parent_id
                        AND expediente_id=NEW.expediente_id;
                ELSE
                    SELECT f.id INTO NEW.expediente_folder_id FROM expediente_folders f
                    JOIN folder_types t ON t.id=f.folder_type_id
                    WHERE f.expediente_id=NEW.expediente_id AND t.name='EXPEDIENTE PRINCIPAL';
                END IF;
            END IF;
            RETURN NEW;
        END;
        $$;
    $function$;
    CREATE TRIGGER section_default_folder BEFORE INSERT ON expediente_section
        FOR EACH ROW EXECUTE FUNCTION assign_section_folder();
    EXECUTE $function$
        CREATE FUNCTION create_principal_folder() RETURNS trigger LANGUAGE plpgsql AS $$
        BEGIN
            INSERT INTO expediente_folders(expediente_id, folder_type_id)
            SELECT NEW.id, id FROM folder_types WHERE name='EXPEDIENTE PRINCIPAL';
            RETURN NEW;
        END;
        $$;
    $function$;
    CREATE TRIGGER expediente_principal_folder AFTER INSERT ON expedientes
        FOR EACH ROW EXECUTE FUNCTION create_principal_folder();
    INSERT INTO app_schema_migrations(version) VALUES ('004_expediente_folders');
END;
$upgrade$;
COMMIT;

-- Consolidated current schema for a new database. Apply once.
BEGIN;

-- A previous installation can leave the enum behind without expedientes.
-- Reuse only an enum with the exact labels and order required by this schema.
DO $migration$
DECLARE
    expected_labels CONSTANT text[] := ARRAY[
        'DENUNCIA_DE_OFICIO',
        'DENUNCIA_DE_PARTE',
        'COMUNICACIONES_DE_ENTIDADES_PUBLICAS',
        'COMUNICACIONES_DE_SANCION_IMPUESTA_POR_PJ_O_MP',
        'APROBADO_POR_ASAMBLEA_GENERAL'
    ];
    actual_labels text[];
BEGIN
    BEGIN
        CREATE TYPE expediente_init_type_enum AS ENUM (
    'DENUNCIA_DE_OFICIO',
    'DENUNCIA_DE_PARTE',
    'COMUNICACIONES_DE_ENTIDADES_PUBLICAS',
    'COMUNICACIONES_DE_SANCION_IMPUESTA_POR_PJ_O_MP',
    'APROBADO_POR_ASAMBLEA_GENERAL'
        );
    EXCEPTION WHEN duplicate_object THEN
        SELECT array_agg(e.enumlabel::text ORDER BY e.enumsortorder)
        INTO actual_labels
        FROM pg_enum e
        WHERE e.enumtypid = 'expediente_init_type_enum'::regtype;

        IF actual_labels IS DISTINCT FROM expected_labels THEN
            RAISE EXCEPTION USING
                ERRCODE = '42804',
                MESSAGE = 'existing expediente_init_type_enum is incompatible with the initial migration';
        END IF;
    END;
END;
$migration$;

CREATE TABLE expedientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description TEXT NOT NULL DEFAULT '',
    opening_date DATE,
    number VARCHAR(50) NOT NULL UNIQUE,
    status VARCHAR(30) NOT NULL DEFAULT 'ABIERTO' CHECK (status IN ('ABIERTO','CERRADO')),
    location VARCHAR(30) NOT NULL DEFAULT 'DIRECCION DE ETICA'
        CHECK (location IN ('DIRECCION DE ETICA','CONSEJO DE ETICA','TRIBUNAL DE HONOR')),
    init_type expediente_init_type_enum,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE expediente_year_counters (
    year INTEGER PRIMARY KEY CHECK (year BETWEEN 1 AND 9999),
    last_number BIGINT NOT NULL CHECK (last_number > 0)
);

CREATE OR REPLACE FUNCTION next_expediente_code(p_year INTEGER) RETURNS VARCHAR(50)
LANGUAGE plpgsql AS $$
DECLARE next_number BIGINT;
BEGIN
    INSERT INTO expediente_year_counters (year, last_number) VALUES (p_year, 1)
    ON CONFLICT (year) DO UPDATE
    SET last_number = expediente_year_counters.last_number + 1
    RETURNING last_number INTO next_number;
    RETURN next_number::TEXT || '-' || p_year::TEXT;
END;
$$;

CREATE OR REPLACE FUNCTION assign_expediente_code() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.opening_date IS NULL THEN
        RAISE EXCEPTION 'opening_date is required to assign expediente number' USING ERRCODE='23502';
    END IF;
    NEW.number := next_expediente_code(EXTRACT(YEAR FROM NEW.opening_date)::INTEGER);
    RETURN NEW;
END;
$$;

CREATE TRIGGER expediente_auto_code BEFORE INSERT ON expedientes
FOR EACH ROW EXECUTE FUNCTION assign_expediente_code();


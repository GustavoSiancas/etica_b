BEGIN;

CREATE TYPE expediente_init_type_enum AS ENUM (
    'DENUNCIA_DE_OFICIO',
    'DENUNCIA_DE_PARTE',
    'COMUNICACIONES_DE_ENTIDADES_PUBLICAS',
    'COMUNICACIONES_DE_SANCION_IMPUESTA_POR_PJ_O_MP',
    'APROBADO_POR_ASAMBLEA_GENERAL'
);

CREATE TABLE expedientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL DEFAULT '',
    opening_date DATE,
    number VARCHAR(50) NOT NULL UNIQUE,
    code VARCHAR(50) NOT NULL UNIQUE,
    status VARCHAR(30) NOT NULL DEFAULT 'OPEN',
    init_type expediente_init_type_enum,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE expediente_year_counters (
    year INTEGER PRIMARY KEY CHECK (year BETWEEN 1 AND 9999),
    last_number BIGINT NOT NULL CHECK (last_number > 0)
);

CREATE FUNCTION next_expediente_code(p_year INTEGER) RETURNS VARCHAR(50)
LANGUAGE plpgsql AS $$
DECLARE next_number BIGINT;
BEGIN
    INSERT INTO expediente_year_counters (year, last_number) VALUES (p_year, 1)
    ON CONFLICT (year) DO UPDATE
    SET last_number = expediente_year_counters.last_number + 1
    RETURNING last_number INTO next_number;
    RETURN next_number::TEXT || '-' || p_year::TEXT;
END;
$$;

CREATE FUNCTION assign_expediente_code() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.code := next_expediente_code(EXTRACT(YEAR FROM statement_timestamp() AT TIME ZONE 'America/Lima')::INTEGER);
    NEW.number := NEW.code;
    RETURN NEW;
END;
$$;

CREATE TRIGGER expediente_auto_code BEFORE INSERT ON expedientes
FOR EACH ROW EXECUTE FUNCTION assign_expediente_code();

CREATE TABLE document_stages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(60) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    sort_order INTEGER NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE document_substages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage_id BIGINT NOT NULL REFERENCES document_stages(id) ON DELETE RESTRICT,
    code VARCHAR(70) NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL,
    sort_order INTEGER NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX idx_substages_stage ON document_substages(stage_id);

CREATE TABLE documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expediente_id BIGINT NOT NULL REFERENCES expedientes(id) ON DELETE RESTRICT,
    name VARCHAR(255) NOT NULL,
    file_url TEXT,
    document_date DATE,
    substage_id BIGINT NOT NULL REFERENCES document_substages(id) ON DELETE RESTRICT,
    status VARCHAR(30) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','PENDING','APPROVED','REJECTED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (id, expediente_id)
);
CREATE INDEX idx_documents_expediente ON documents(expediente_id);
CREATE INDEX idx_documents_substage ON documents(substage_id);

CREATE TABLE denunciantes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE denunciados (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE expediente_denunciantes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expediente_id BIGINT NOT NULL REFERENCES expedientes(id) ON DELETE RESTRICT,
    denunciante_id BIGINT NOT NULL REFERENCES denunciantes(id) ON DELETE RESTRICT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (expediente_id, denunciante_id),
    UNIQUE (id, expediente_id)
);
CREATE INDEX idx_exp_denunciante_person ON expediente_denunciantes(denunciante_id);

CREATE TABLE expediente_denunciados (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expediente_id BIGINT NOT NULL REFERENCES expedientes(id) ON DELETE RESTRICT,
    denunciado_id BIGINT NOT NULL REFERENCES denunciados(id) ON DELETE RESTRICT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (expediente_id, denunciado_id),
    UNIQUE (id, expediente_id)
);
CREATE INDEX idx_exp_denunciado_person ON expediente_denunciados(denunciado_id);

CREATE TABLE document_denunciantes (
    document_id BIGINT NOT NULL,
    expediente_denunciante_id BIGINT NOT NULL,
    expediente_id BIGINT NOT NULL,
    PRIMARY KEY (document_id, expediente_denunciante_id),
    FOREIGN KEY (document_id, expediente_id) REFERENCES documents(id, expediente_id) ON DELETE RESTRICT,
    FOREIGN KEY (expediente_denunciante_id, expediente_id) REFERENCES expediente_denunciantes(id, expediente_id) ON DELETE RESTRICT
);
CREATE INDEX idx_doc_denunciante_participant ON document_denunciantes(expediente_denunciante_id);
CREATE INDEX idx_doc_denunciante_exp ON document_denunciantes(expediente_id);

CREATE TABLE document_denunciados (
    document_id BIGINT NOT NULL,
    expediente_denunciado_id BIGINT NOT NULL,
    expediente_id BIGINT NOT NULL,
    PRIMARY KEY (document_id, expediente_denunciado_id),
    FOREIGN KEY (document_id, expediente_id) REFERENCES documents(id, expediente_id) ON DELETE RESTRICT,
    FOREIGN KEY (expediente_denunciado_id, expediente_id) REFERENCES expediente_denunciados(id, expediente_id) ON DELETE RESTRICT
);
CREATE INDEX idx_doc_denunciado_participant ON document_denunciados(expediente_denunciado_id);
CREATE INDEX idx_doc_denunciado_exp ON document_denunciados(expediente_id);

CREATE TABLE expediente_participant_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expediente_id BIGINT NOT NULL REFERENCES expedientes(id) ON DELETE RESTRICT,
    participant_type VARCHAR(20) NOT NULL CHECK (participant_type IN ('DENUNCIANTE','DENUNCIADO')),
    participant_id BIGINT NOT NULL,
    action VARCHAR(30) NOT NULL CHECK (action IN ('ADDED','REMOVED','UPDATED')),
    reason TEXT,
    created_by BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    previous_name VARCHAR(255),
    new_name VARCHAR(255),
    denunciante_id BIGINT GENERATED ALWAYS AS (CASE WHEN participant_type = 'DENUNCIANTE' THEN participant_id END) STORED REFERENCES denunciantes(id) ON DELETE RESTRICT,
    denunciado_id BIGINT GENERATED ALWAYS AS (CASE WHEN participant_type = 'DENUNCIADO' THEN participant_id END) STORED REFERENCES denunciados(id) ON DELETE RESTRICT,
    CHECK (
        (action = 'ADDED' AND previous_name IS NULL AND new_name IS NOT NULL) OR
        (action = 'REMOVED' AND previous_name IS NOT NULL AND new_name IS NULL) OR
        (action = 'UPDATED' AND previous_name IS NOT NULL AND new_name IS NOT NULL)
    )
);
CREATE INDEX idx_history_expediente_time ON expediente_participant_history(expediente_id, created_at, id);
CREATE INDEX idx_history_participant ON expediente_participant_history(participant_type, participant_id);
CREATE INDEX idx_history_denunciante ON expediente_participant_history(denunciante_id);
CREATE INDEX idx_history_denunciado ON expediente_participant_history(denunciado_id);

CREATE FUNCTION protect_participant_history() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE'
       AND current_setting('app.demo_reset', TRUE) = 'on'
       AND OLD.reason = 'Registro inicial de datos ficticios para pruebas.' THEN
        RETURN OLD;
    END IF;
    RAISE EXCEPTION 'Participant history is append-only';
END;
$$;
CREATE TRIGGER participant_history_immutable BEFORE UPDATE OR DELETE ON expediente_participant_history
    FOR EACH ROW EXECUTE FUNCTION protect_participant_history();
CREATE TRIGGER participant_history_no_truncate BEFORE TRUNCATE ON expediente_participant_history
    FOR EACH STATEMENT EXECUTE FUNCTION protect_participant_history();

CREATE TABLE escritos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    type VARCHAR(100) NOT NULL DEFAULT '',
    expediente_number VARCHAR(50) NOT NULL,

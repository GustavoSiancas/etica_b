);
CREATE TABLE denunciados (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    document_type VARCHAR(3),
    document_number VARCHAR(20),

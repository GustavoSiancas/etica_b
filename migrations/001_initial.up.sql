CREATE TABLE documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expediente_id BIGINT NOT NULL REFERENCES expedientes(id) ON DELETE RESTRICT,
    name VARCHAR(255) NOT NULL,
    file_url TEXT,
    document_date DATE,
    stage TEXT NOT NULL CHECK (btrim(stage) <> ''),
    type TEXT NOT NULL CHECK (btrim(type) <> ''),
    status VARCHAR(30) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','PENDING','APPROVED','REJECTED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_documents_expediente ON documents(expediente_id);


CREATE TABLE denunciantes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    document_type VARCHAR(3),
    document_number VARCHAR(20),
    CONSTRAINT denunciantes_document_check CHECK ((document_type IS NULL AND document_number IS NULL) OR (document_type IS NOT NULL AND document_type IN ('DNI','RUC','CE') AND document_number IS NOT NULL AND document_number ~ '^[0-9]{1,20}$')),
    is_demo BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE denunciados (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    document_type VARCHAR(3),
    document_number VARCHAR(20),
    registration_number BIGINT CHECK (registration_number > 0),
    CONSTRAINT denunciados_document_check CHECK ((document_type IS NULL AND document_number IS NULL) OR (document_type IS NOT NULL AND document_type IN ('DNI','CE') AND document_number IS NOT NULL AND document_number ~ '^[0-9]{1,20}$')),
    is_demo BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE expediente_denunciantes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expediente_id BIGINT NOT NULL REFERENCES expedientes(id) ON DELETE RESTRICT,
    denunciante_id BIGINT NOT NULL REFERENCES denunciantes(id) ON DELETE RESTRICT,
    UNIQUE (expediente_id, denunciante_id)
);
CREATE INDEX idx_exp_denunciante_person ON expediente_denunciantes(denunciante_id);

CREATE TABLE expediente_denunciados (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expediente_id BIGINT NOT NULL REFERENCES expedientes(id) ON DELETE RESTRICT,
    denunciado_id BIGINT NOT NULL REFERENCES denunciados(id) ON DELETE RESTRICT,
    UNIQUE (expediente_id, denunciado_id)
);
CREATE INDEX idx_exp_denunciado_person ON expediente_denunciados(denunciado_id);

CREATE TABLE escritos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    type VARCHAR(100) NOT NULL DEFAULT '',
    expediente_number VARCHAR(50) NOT NULL,
    document_date DATE,
    file_url TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'NUEVA' CHECK (status IN ('NUEVA','ATENDIDA')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_escritos_created_at_id ON escritos(created_at, id);

CREATE TABLE escrito_denunciantes (
    escrito_id BIGINT NOT NULL REFERENCES escritos(id) ON DELETE CASCADE,
    denunciante_id BIGINT NOT NULL REFERENCES denunciantes(id) ON DELETE RESTRICT,
    PRIMARY KEY (escrito_id, denunciante_id)
);
CREATE INDEX idx_escrito_denunciantes_person ON escrito_denunciantes(denunciante_id);

CREATE TABLE escrito_denunciados (
    escrito_id BIGINT NOT NULL REFERENCES escritos(id) ON DELETE CASCADE,
    denunciado_id BIGINT NOT NULL REFERENCES denunciados(id) ON DELETE RESTRICT,
    PRIMARY KEY (escrito_id, denunciado_id)
);
CREATE INDEX idx_escrito_denunciados_person ON escrito_denunciados(denunciado_id);


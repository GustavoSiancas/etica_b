BEGIN;

CREATE TYPE expediente_init_type_enum AS ENUM (
    'DENUNCIA_DE_OFICIO',
    'DENUNCIA_DE_PARTE',
    'COMUNICACIONES_DE_ENTIDADES_PUBLICAS',
    'COMUNICACIONES_DE_SANCION_IMPUESTA_POR_PJ_O_MP',
    'APROBADO_POR_ASAMBLEA_GENERAL'
);

CREATE TABLE expedientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description TEXT NOT NULL DEFAULT '',
    opening_date DATE,
    number VARCHAR(50) NOT NULL UNIQUE,
    code VARCHAR(50) NOT NULL UNIQUE,
    status VARCHAR(30) NOT NULL DEFAULT 'OPEN',
    init_type expediente_init_type_enum,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE expediente_year_counters (
    year INTEGER PRIMARY KEY CHECK (year BETWEEN 1 AND 9999),
    last_number BIGINT NOT NULL CHECK (last_number > 0)
);

CREATE FUNCTION next_expediente_code(p_year INTEGER) RETURNS VARCHAR(50)
LANGUAGE plpgsql AS $$
DECLARE next_number BIGINT;
BEGIN
    INSERT INTO expediente_year_counters (year, last_number) VALUES (p_year, 1)
    ON CONFLICT (year) DO UPDATE
    SET last_number = expediente_year_counters.last_number + 1
    RETURNING last_number INTO next_number;
    RETURN next_number::TEXT || '-' || p_year::TEXT;
END;
$$;

CREATE FUNCTION assign_expediente_code() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.code := next_expediente_code(EXTRACT(YEAR FROM statement_timestamp() AT TIME ZONE 'America/Lima')::INTEGER);
    NEW.number := NEW.code;
    RETURN NEW;
END;
$$;

CREATE TRIGGER expediente_auto_code BEFORE INSERT ON expedientes
FOR EACH ROW EXECUTE FUNCTION assign_expediente_code();

CREATE TABLE document_stages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(60) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    sort_order INTEGER NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE document_substages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage_id BIGINT NOT NULL REFERENCES document_stages(id) ON DELETE RESTRICT,
    code VARCHAR(70) NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL,
    sort_order INTEGER NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX idx_substages_stage ON document_substages(stage_id);

CREATE TABLE document_types (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR(70) NOT NULL UNIQUE,
 name VARCHAR(150) NOT NULL,
 sort_order INTEGER NOT NULL,
 is_active BOOLEAN NOT NULL DEFAULT TRUE
);

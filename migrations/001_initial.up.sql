CREATE TABLE expediente_section (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expediente_id BIGINT NOT NULL REFERENCES expedientes(id) ON DELETE RESTRICT,
    expediente_section_parent_id BIGINT,
    name TEXT NOT NULL CHECK (btrim(name) <> ''),
    type TEXT NOT NULL CHECK (btrim(type) <> ''),
    document_date DATE,
    sort_order INTEGER NOT NULL CHECK (sort_order >= 0),
    color_hex VARCHAR(7) NOT NULL DEFAULT '#808080'
        CHECK (color_hex ~ '^#[0-9A-Fa-f]{6}$'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (expediente_id, id),
    CHECK (expediente_section_parent_id IS DISTINCT FROM id),
    FOREIGN KEY (expediente_id, expediente_section_parent_id)
        REFERENCES expediente_section(expediente_id, id) ON DELETE RESTRICT
);
CREATE INDEX idx_expediente_section_tree
    ON expediente_section(expediente_id, expediente_section_parent_id, sort_order, id);

-- Serialize hierarchy edits within each expediente, including concurrent transactions.
-- UNION terminates traversal even when the proposed hierarchy contains a cycle.
CREATE FUNCTION validate_expediente_section_tree() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    UPDATE expedientes SET updated_at = updated_at WHERE id = NEW.expediente_id;
    IF EXISTS (
        WITH RECURSIVE ancestors(id) AS (
            SELECT expediente_section_parent_id
            FROM expediente_section WHERE id = NEW.id
            UNION
            SELECT s.expediente_section_parent_id
            FROM expediente_section s JOIN ancestors a ON s.id = a.id
            WHERE s.expediente_id = NEW.expediente_id
        )
        SELECT 1 FROM ancestors WHERE id = NEW.id
    ) THEN
        RAISE EXCEPTION 'section hierarchy cannot contain cycles' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER expediente_section_tree_check
    AFTER INSERT OR UPDATE ON expediente_section
    FOR EACH ROW EXECUTE FUNCTION validate_expediente_section_tree();

